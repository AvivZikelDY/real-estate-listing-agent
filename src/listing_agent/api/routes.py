@router.get(
    "/model_architecture",
    response_class=Response,
    responses={200: {"content": {"image/png": {}}}},
)
def model_architecture() -> Response:
    """Return the architecture diagram PNG, generated by

    `scripts/generate_architecture_image.py`. Serves the actual image
    bytes (never a JSON file path) with `Content-Type: image/png`.
    """
    if not ARCHITECTURE_IMAGE_PATH.is_file():
        raise HTTPException(
            status_code=500,
            detail=(
                "Architecture diagram not found. Run "
                "scripts/generate_architecture_image.py to generate it."
            ),
        )
    return Response(content=ARCHITECTURE_IMAGE_PATH.read_bytes(), media_type="image/png")


def _get_step_tracer_dependency() -> StepTracer:
    """FastAPI dependency producing a fresh `StepTracer` per request."""
    return StepTracer()


def _get_llm_client_dependency(
    tracer: StepTracer = Depends(_get_step_tracer_dependency),
) -> LLMClient:
    """FastAPI dependency wrapping `get_llm_client`, overridable in tests.

    FastAPI caches dependency results per request, so this receives the
    same `StepTracer` instance the `execute` route uses, letting
    `LLModClient` record a bounded repair attempt as its own step.
    """
    return get_llm_client(step_tracer=tracer)


def _get_tool_executor_dependency() -> ToolExecutor:
    """FastAPI dependency wrapping `get_tool_executor`, overridable in tests."""
    return get_tool_executor()


def _get_settings_dependency() -> Settings:
    """FastAPI dependency wrapping `get_settings`, overridable in tests."""
    return get_settings()


def _llm_steps(tracer: StepTracer) -> list[StepTrace]:
    """Only the LLM-module steps are surfaced in the public `/api/execute` response.

    `step_tracer` also records `tool` and `deterministic` steps internally
    (used to build the Evidence Bundle), but a normal successful run must
    report exactly two steps here: `triage_planner`, then `report_writer`.
    """
    return [step for step in tracer.get_steps() if step.type == "llm"]


@router.post("/execute", response_model=ExecuteResponse)
async def execute(
    request: ExecuteRequest,
    llm_client: LLMClient = Depends(_get_llm_client_dependency),
    tool_executor: ToolExecutor = Depends(_get_tool_executor_dependency),
    tracer: StepTracer = Depends(_get_step_tracer_dependency),
    settings: Settings = Depends(_get_settings_dependency),
) -> ExecuteResponse:
    """Run the full agent pipeline and return the required four-field response."""
    try:
        result = await asyncio.wait_for(
            run_agent_pipeline(
                request.prompt,
                llm_client=llm_client,
                tool_executor=tool_executor,
                tracer=tracer,
                settings=settings,
            ),
            timeout=settings.request_deadline_seconds,
        )
    except RequestLimitError as exc:
        return ExecuteResponse(
            status="error", error=exc.message, response=None, steps=_llm_steps(tracer)
        )
    except PlanValidationError as exc:
        return ExecuteResponse(
            status="error", error=str(exc), response=None, steps=_llm_steps(tracer)
        )
    except TimeoutError:
        return ExecuteResponse(
            status="error",
            error=(
                f"Request exceeded the time limit of "
                f"{settings.request_deadline_seconds:.0f} seconds."
            ),
            response=None,
            steps=_llm_steps(tracer),
        )
    except Exception as exc:  # last-resort: keep the four-field contract intact
        return ExecuteResponse(
            status="error",
            error=f"Agent execution failed: {exc}",
            response=None,
            steps=_llm_steps(tracer),
        )

    return ExecuteResponse(
        status="ok", error=None, response=result.report, steps=_llm_steps(tracer)
    )
